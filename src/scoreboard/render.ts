/**
 * The scoreboard as Markdown, a pure function of the parsed runs: the same files always give the same text, so
 * `pnpm scoreboard --check` can tell whether the committed table is the one the files produce. Numerators and
 * denominators are always shown, and a small sample says it is one.
 */
import { metricsFor, type Measure, type Ratio, type SplitMetrics } from "./aggregate.js";
import type { ScoreboardRun, Split } from "./results.js";

/** Below this many cases a ratio is a small sample, not a reliability estimate. */
export const SMALL_SAMPLE = 30;

export function formatRatio(r: Ratio): string {
  if (r.of === 0) return "n/a (no cases)";
  return `${r.passed}/${r.of} (${Math.round((r.passed / r.of) * 100)}%)`;
}

function formatMeasure(m: Measure, unit: "usd" | "ms"): string {
  if (m.n === 0 || m.median === undefined || m.mean === undefined) return "not recorded";
  const f = (v: number): string => (unit === "usd" ? `$${v.toFixed(4)}` : v >= 1000 ? `${(v / 1000).toFixed(1)} s` : `${Math.round(v)} ms`);
  return `median ${f(m.median)}, mean ${f(m.mean)} (n=${m.n})`;
}

function table(m: SplitMetrics): string[] {
  const rows: [string, string, string][] = [
    ["Triage accuracy", formatRatio(m.triageAccuracy), "act / notify / decline matches the expected call"],
    ["Correct declines", formatRatio(m.correctDeclines), "noise declined and no pull request opened"],
    ["Patch pass rate (code fixes)", formatRatio(m.patchPassRate), "the proposed patch passes the private evaluator test"],
    ["Index heal", formatRatio(m.indexHeal), "deterministic; reported apart from the patch pass rate"],
    ["Reviewer catch rate", formatRatio(m.reviewerCatchRate), "planted bad patches the reviewer blocked"],
    ["Cost per case", formatMeasure(m.costUsd, "usd"), "every case that recorded it, errored and timed-out ones included"],
    ["Latency per case", formatMeasure(m.latencyMs, "ms"), "every case that recorded it, errored and timed-out ones included"],
    ["Detection to pull request", formatMeasure(m.detectionToPrMs, "ms"), "completed cases that recorded it"],
  ];
  return ["| Metric | Result | Meaning |", "| --- | --- | --- |", ...rows.map(([a, b, c]) => `| ${a} | ${b} | ${c} |`)];
}

function section(run: ScoreboardRun, split: Split): string[] {
  const m = metricsFor(run, split);
  if (m.cases === 0) return [];
  const lines = [`### ${split === "held-out" ? "Held-out cases" : "Tuning cases"} (${m.cases})`, "", ...table(m), ""];
  const failed = [m.errors > 0 && `${m.errors} errored`, m.timeouts > 0 && `${m.timeouts} timed out`].filter(Boolean);
  if (failed.length > 0) lines.push(`${failed.join(" and ")}: counted as failures above, not left out.`, "");
  const ratios = [m.triageAccuracy, m.correctDeclines, m.patchPassRate, m.indexHeal, m.reviewerCatchRate].filter((r) => r.of > 0);
  if (ratios.some((r) => r.of < SMALL_SAMPLE)) {
    lines.push(`Small sample: fewer than ${SMALL_SAMPLE} cases behind at least one ratio. These numbers describe this corpus, not production reliability.`, "");
  }
  return lines;
}

const configuration = (run: ScoreboardRun): string =>
  Object.entries(run.configuration)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `${k}=${String(v)}`)
    .join(", ") || "none recorded";

export function renderRun(run: ScoreboardRun): string[] {
  return [
    `## ${run.ranAt.slice(0, 10)} · ${run.model} · run ${run.runId}`,
    "",
    `- Corpus ${run.corpusVersion}; app revision \`${run.appRevision}\`; Starfish revision \`${run.starfishRevision}\`.`,
    `- Configuration: ${configuration(run)}.`,
    `- ${run.cases.length} cases, held-out ones frozen by hash before tuning.`,
    "",
    ...section(run, "held-out"),
    ...section(run, "tuning"),
  ];
}

/** Newest run first. With no runs it says so: there is no table to show, and none is made up. */
export function renderScoreboard(runs: readonly ScoreboardRun[]): string {
  const head = [
    "# Scoreboard",
    "",
    "Generated by `pnpm scoreboard` from the files in `scoreboard/results/`. Do not edit by hand: the numbers quoted in the README, the deck and the video are the ones in this file.",
    "",
  ];
  if (runs.length === 0) return [...head, "No runs recorded yet.", ""].join("\n");
  const ordered = [...runs].sort((a, b) => b.ranAt.localeCompare(a.ranAt) || a.runId.localeCompare(b.runId));
  return [...head, ...ordered.flatMap(renderRun)].join("\n");
}
